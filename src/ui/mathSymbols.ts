/** Flattens and filters math symbol categories matching a case-insensitive query. */
export function filterMathSymbols(
  query: string,
  translate?: (key: string) => string,
): MathSymbolCategory[] {
  const q = query.trim().toLowerCase();
  if (!q) return MATH_SYMBOL_CATEGORIES;
  const out: MathSymbolCategory[] = [];
  for (const cat of MATH_SYMBOL_CATEGORIES) {
    const catLabel = (translate ? translate(cat.label) : cat.label).toLowerCase();
    const catMatches = catLabel.includes(q);
    const symbols = catMatches
      ? cat.symbols
      : cat.symbols.filter((s) =>
          s.code.toLowerCase().includes(q)
          || s.name.toLowerCase().includes(q)
          || s.display.toLowerCase().includes(q)
          || (s.pkg && s.pkg.toLowerCase().includes(q))
          || (s.keywords && s.keywords.some((k) => k.toLowerCase().includes(q))),
        );
    if (symbols.length > 0) {
      out.push({ ...cat, symbols });
    }
  }
  return out;
}

/** Insertion string for a symbol (uses snippet tab-stops when defined, otherwise raw code). */
export function insertionTextForSymbol(symbol: MathSymbol): string {
  return symbol.snippet ?? symbol.code;
}
