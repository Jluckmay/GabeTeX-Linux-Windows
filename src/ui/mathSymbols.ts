/**
 * Complete categorized catalog of LaTeX math symbols (`article`, `amsmath`,
 * `amssymb`, `amsfonts`, `mathrsfs`, `gensymb`) for click and drag-and-drop
 * insertion into the LaTeX editor.
 */

export interface MathSymbol {
  /** Visual glyph or compact representation rendered on the grid tile. */
  display: string;
  /** Canonical LaTeX code shown in tooltips/preview and used as default text. */
  code: string;
  /** Optional snippet template with `${1}` / `${2}` tab stops for insertion. */
  snippet?: string;
  /** English symbol name / description (used for search and accessibility). */
  name: string;
  /** Extra search terms (English & Portuguese aliases, notation names). */
  keywords?: string[];
  /** Optional LaTeX package required beyond core math mode. */
  pkg?: string;
}

export interface MathSymbolCategory {
  id: string;
  /** i18n key for the category heading. */
  label: string;
  /** Representative icon glyph shown next to the category title. */
  icon: string;
  symbols: MathSymbol[];
}

